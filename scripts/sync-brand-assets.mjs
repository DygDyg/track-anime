import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const logoPath = path.join(root, "public", "logo.png");
const generatedPath = path.join(root, "src", "lib", "site-brand.generated.ts");

if (!fs.existsSync(logoPath)) {
  console.error("sync-brand-assets: public/logo.png not found");
  process.exit(1);
}

const logoVersion = crypto.createHash("md5").update(fs.readFileSync(logoPath)).digest("hex").slice(0, 12);

async function writeSquarePng(source, size, outPath) {
  await source
    .clone()
    .resize(size, size, {
      fit: "contain",
      background: { r: 0, g: 0, b: 0, alpha: 0 },
    })
    .png()
    .toFile(outPath);
}

async function writeFaviconIco(source, outPath) {
  const sizes = [16, 32, 48];
  const pngBuffers = await Promise.all(
    sizes.map((size) =>
      source
        .clone()
        .resize(size, size, {
          fit: "contain",
          background: { r: 0, g: 0, b: 0, alpha: 0 },
        })
        .png()
        .toBuffer(),
    ),
  );

  const entries = pngBuffers.map((buffer, index) => ({
    size: sizes[index],
    buffer,
  }));

  const headerSize = 6 + entries.length * 16;
  let offset = headerSize;
  const dir = Buffer.alloc(entries.length * 16);
  const images = [];

  for (let i = 0; i < entries.length; i += 1) {
    const { size, buffer } = entries[i];
    const entryOffset = i * 16;
    dir.writeUInt8(size === 256 ? 0 : size, entryOffset);
    dir.writeUInt8(size === 256 ? 0 : size, entryOffset + 1);
    dir.writeUInt8(0, entryOffset + 2);
    dir.writeUInt8(0, entryOffset + 3);
    dir.writeUInt16LE(1, entryOffset + 4);
    dir.writeUInt16LE(32, entryOffset + 6);
    dir.writeUInt32LE(buffer.length, entryOffset + 8);
    dir.writeUInt32LE(offset, entryOffset + 12);
    images.push(buffer);
    offset += buffer.length;
  }

  const header = Buffer.alloc(6);
  header.writeUInt16LE(0, 0);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(entries.length, 4);

  fs.writeFileSync(outPath, Buffer.concat([header, dir, ...images]));
}

const source = sharp(logoPath, { animated: false });

const pngTargets = [
  { size: 512, path: path.join(root, "src", "app", "icon.png") },
  { size: 180, path: path.join(root, "src", "app", "apple-icon.png") },
  { size: 180, path: path.join(root, "public", "apple-touch-icon.png") },
  { size: 192, path: path.join(root, "public", "icon-192.png") },
  { size: 32, path: path.join(root, "public", "favicon-32.png") },
  { size: 16, path: path.join(root, "public", "favicon-16.png") },
];

for (const target of pngTargets) {
  await writeSquarePng(source, target.size, target.path);
  console.log(`sync-brand-assets: ${path.relative(root, target.path)} (${target.size}x${target.size})`);
}

await writeFaviconIco(source, path.join(root, "public", "favicon.ico"));
console.log("sync-brand-assets: public/favicon.ico");

await writeFaviconIco(source, path.join(root, "src", "app", "favicon.ico"));
console.log("sync-brand-assets: src/app/favicon.ico");

await writeSquarePng(source, 512, path.join(root, "public", "icon.png"));
console.log("sync-brand-assets: public/icon.png (512x512)");

fs.writeFileSync(
  generatedPath,
  `// Generated by scripts/sync-brand-assets.mjs — do not edit manually.\nexport const SITE_LOGO_VERSION = "${logoVersion}";\n`,
);
console.log(`sync-brand-assets: ${path.relative(root, generatedPath)} (${logoVersion})`);
console.log("sync-brand-assets: done");
